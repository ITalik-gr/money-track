-- Масовий прогон — це задача, яка звітує ПРОГРЕС, а не «готово / не готово».
--
-- `ai_jobs` (0035) тримає одну генерацію: поставили, alarm узяв, записав результат. Ре-світ і
-- батч-enrich мають іншу природу — вони йдуть пачками, між пачками лишаються незавершеними, і
-- єдине осмислене питання про них — «скільки зроблено зі скількох». Без цих двох колонок стан
-- «зроблено 300 із 1200» ніде не живе: рядок або 'running' (і нічого не каже), або 'done'.
--
-- ЧОМУ ДВІ КОЛОНКИ, А НЕ ВІДСОТОК: відсоток — це похідне, а знаменник тут потрібен сам по собі.
-- «370 із 1200» і «31%» читаються по-різному, коли прогін зупинився: перше каже, скільки роботи
-- лишилось, друге — ні. Крім того, `progress_done` мусить СТРОГО ЗРОСТАТИ між пачками, і саме це
-- є запобіжником проти вічного будильника (`jobs.ts`): пачка, яка нічого не зрушила, зупиняє
-- задачу, а не крутить її далі. З відсотка, округленого до цілих, цю перевірку зробити не можна.
--
-- NULL = це не масова задача. Звичайна генерація (advisor/report/budget) лишає обидві порожніми,
-- і клієнт відрізняє одне від одного саме за наявністю знаменника, а не за видом задачі.
ALTER TABLE ai_jobs ADD COLUMN progress_done  INTEGER;
ALTER TABLE ai_jobs ADD COLUMN progress_total INTEGER;
