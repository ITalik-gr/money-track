-- §P2.1 кроки 2-4: тип цілі, авто-поповнення, і все, що з них рахується.
--
-- `kind` існує тому, що математика «коли встигну» різна за суттю:
--   save_up      — накопичити суму (дефолт, поведінка як була);
--   debt_payoff  — погасити борг: «прогрес» рахується так само, але формулювання інше
--                  (закрито X із Y боргу), і «встигнути» тут значить «закрити раніше»;
--   sinking_fund — фонд під регулярну майбутню витрату (страховка, шини): він не «закінчується»,
--                  тож досягнення цілі — не привід її архівувати, і ETA міряє наступний цикл.
--
-- Авто-поповнення живе ТУТ, а не окремою таблицею правил: одна ціль — щонайбільше одне
-- правило, і таблиця з одним рядком на ціль була б джойном заради нічого.
ALTER TABLE savings_goals ADD COLUMN kind TEXT NOT NULL DEFAULT 'save_up';

-- NULL = вимкнено. 'fixed' — `autofill_value` у копійках; 'income_pct' — відсоток (1..100)
-- від доходу ПОПЕРЕДНЬОГО повного місяця.
ALTER TABLE savings_goals ADD COLUMN autofill_kind TEXT;
ALTER TABLE savings_goals ADD COLUMN autofill_value INTEGER;
-- Місяць (`YYYY-MM`), за який авто-внесок уже зроблено. Саме місяць, а не таймстамп: крон
-- може прогнатись двічі (ретрай, ручний виклик), і ключ «за який період» — єдине, що робить
-- нарахування ідемпотентним. З таймстампом другий прогін просто додав би ще один внесок.
ALTER TABLE savings_goals ADD COLUMN autofill_last_ym TEXT;
