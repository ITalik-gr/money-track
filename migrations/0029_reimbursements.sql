-- §COMPENSATION: «мені скинули за це гроші» — компенсація частини (або всієї) витрати.
--
-- Ситуація: користувач платить за спільне (вечеря, спільна покупка, оренда), а потім йому
-- переказують частину. Досі витрата рахувалась ПОВНІСТЮ його, а вхідний переказ або тонув
-- у бакеті «Перекази і зняття», або (якщо категоризований) роздував дохід. Тобто одна
-- операція брехала двічі.
--
-- Модель — дзеркальна пара двох колонок, БЕЗ окремої таблиці:
--   transactions.reimbursed    — скільки з ЦІЄЇ витрати компенсували (додатне, копійки,
--                                у валюті операції). Може бути виставлене вручну — коли
--                                віддали готівкою і надходження в банку нема.
--   transactions.reimburses_id — ЦЯ операція (надходження) є компенсацією за витрату X.
--                                Кілька людей за одну вечерю = кілька надходжень з тим самим id.
--
-- Чому не таблиця звʼязків: канонічна сума витрати рахується в `EFF_AMOUNT` (stats.ts) — це
-- найгарячіший вираз проєкту. Колонка додає туди одне `+ COALESCE(t.reimbursed, 0)`, тоді як
-- join тягнув би ще один агрегат у КОЖЕН аналітичний запит.
ALTER TABLE transactions ADD COLUMN reimbursed INTEGER NOT NULL DEFAULT 0;
ALTER TABLE transactions ADD COLUMN reimburses_id TEXT;

CREATE INDEX IF NOT EXISTS idx_tx_reimburses ON transactions(reimburses_id);
