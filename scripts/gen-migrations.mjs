// Embeds migrations/*.sql into a generated TS module so the Durable Object can run the
// exact same schema the D1 database runs.
//
// Why generate a file instead of importing the .sql at build time: the schema is the one
// thing that must not depend on bundler behaviour. A bundler-specific trick
// (`import.meta.glob`, `?raw`, wrangler `rules`) fails at runtime inside the DO constructor
// if the build path ever changes — and it surfaces as "this user's database is empty", the
// worst possible failure mode. This project already has two plausible build paths
// (@cloudflare/vite-plugin builds the worker today, via the redirected config in
// `.wrangler/deploy/config.json`; a plain `wrangler deploy` would use esbuild instead), and
// `tsconfig.worker.json` does not even load Vite's types. A committed .ts module is the only
// form every path treats identically — and it is diffable in review.
//
// Usage:
//   node scripts/gen-migrations.mjs          → (re)write the generated module
//   node scripts/gen-migrations.mjs --check  → fail if it is stale (wired into `npm run check`)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "migrations");
const outFile = join(root, "worker", "do", "migrations.generated.ts");

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort(); // filenames are zero-padded (0001…0030), so lexical sort == apply order

const entries = files.map((name) => {
  const sql = readFileSync(join(migrationsDir, name), "utf8");
  return { name, sql };
});

const body = `// GENERATED BY scripts/gen-migrations.mjs — DO NOT EDIT BY HAND.
// Source of truth: migrations/*.sql. Regenerate with \`node scripts/gen-migrations.mjs\`;
// \`npm run check\` fails when this file drifts from the directory.
export interface EmbeddedMigration {
  /** File name, e.g. "0001_init.sql". Doubles as the applied-migrations key. */
  readonly name: string;
  readonly sql: string;
}

export const MIGRATIONS: readonly EmbeddedMigration[] = [
${entries.map((e) => `  { name: ${JSON.stringify(e.name)}, sql: ${JSON.stringify(e.sql)} },`).join("\n")}
];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    /* missing file == stale */
  }
  if (current !== body) {
    console.error(
      `✗ ${outFile.replace(root + "/", "")} is stale.\n` +
        `  Run: node scripts/gen-migrations.mjs\n` +
        `  (a migration was added or edited without regenerating the DO's copy)`,
    );
    process.exit(1);
  }
  console.log(`✓ migrations embed up to date (${entries.length} files)`);
} else {
  writeFileSync(outFile, body);
  console.log(`✓ wrote ${outFile.replace(root + "/", "")} (${entries.length} migrations)`);
}
